import nltk
import re
# NOTE: The Tree class is necessary for creating the structure
from nltk import Tree

# --- INPUT: The sentence as a list of tagged words ---
# We'll use the tagged words directly for this chunking method
sentence_tagged = [('A', 'DT'), ('beautiful', 'JJ'), ('flower', 'NN'),
                   ('bloomed', 'VBD'), ('near', 'IN'), ('the', 'DT'),
                   ('tall', 'JJ'), ('tree', 'NN')]

# Reconstruct the sentence words for display
sentence_words = [word for word, tag in sentence_tagged]
print(f"Input Sentence: {' '.join(sentence_words)}\n")
print(f"Input Tagged Sentence: {sentence_tagged}\n")


# --- INTERNAL PROCESSING: Parse Tree Construction (as before) ---
# The correct bracketed string representation of the parse tree
bracketed_tree_string = "(S (NP (DT A) (JJ beautiful) (NN flower)) (VP (VBD bloomed) (PP (IN near) (NP (DT the) (JJ tall) (NN tree)))))"

# Create an NLTK Tree object from the bracketed string
try:
    tree = Tree.fromstring(bracketed_tree_string)

    # 1. Print the ASCII (text-based) drawing
    print("## 🌳 ASCII Tree Representation (Text Drawing):")
    tree.pretty_print()
    print("-" * 50)

    # 2. Print the standard bracketed notation
    print("## 📝 Bracketed String Representation:")
    print(tree)
    print("-" * 50)

    # 3. Code to generate the graphical drawing (Requires NLTK, Matplotlib, and Ghostscript locally)
    print("## 🖼️ Graphical Drawing Instructions:")
    print("To see the visual tree diagram in a new window, you must run this command in your local Python environment:")
    # tree.draw()
    print("-" * 50)

    # 4. Perform Noun Phrase Chunking using NLTK's RegexpParser (as before)
    print("## 📦 Noun Phrase Chunking (NLTK RegexpParser):")
    grammar = "NP: {<DT>?<JJ>*<NN>}"
    cp = nltk.RegexpParser(grammar)
    chunked_tree_nltk = cp.parse(sentence_tagged) # Use the tagged sentence directly
    print(chunked_tree_nltk)
    print("-" * 50)

    # 5. Perform Noun Phrase Chunking using the provided regex and loop
    print("## 📦 Noun Phrase Chunking (Manual Regex and Loop):")
    # This is the user's provided chunking logic
    chunks_manual = []
    i = 0
    while i < len(sentence_tagged):
        # Check for the start of a potential NP (optional DT, followed by JJ*)
        if sentence_tagged[i][1] == 'DT' or sentence_tagged[i][1] == 'JJ':
            start_index = i
            # Skip optional DT
            if sentence_tagged[i][1] == 'DT':
                i += 1
                if i == len(sentence_tagged): continue # Avoid index error at the end

            # Skip zero or more JJs
            while i < len(sentence_tagged) and sentence_tagged[i][1] == 'JJ':
                i += 1

            # Check for the required NN at the end
            if i < len(sentence_tagged) and sentence_tagged[i][1] == 'NN':
                chunks_manual.append(sentence_tagged[start_index : i+1])
                # i is already at the position after the NN, so the loop's increment is fine
            else:
                 # If no NN is found after DT/JJ sequence, move to the next word after the start index
                 i = start_index + 1
        else:
            # If the current word is not the start of a potential NP, move to the next word
            i += 1


    for chunk in chunks_manual:
        print("Chunk:", chunk)
    print("-" * 50)

except Exception as e:
    # This block handles potential errors if NLTK is not properly set up
    print(f"Error during processing: {e}")
