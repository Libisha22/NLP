from collections import Counter

text = "the cat sat on the mat"
words = text.split()

uni = Counter(words)
bi = Counter(zip(words, words[1:]))
V = len(uni)

def P(w1, w2):
    return (bi[(w1, w2)] + 1) / (uni[w1] + V)

print("P(cat | the) =", P("the", "cat"))
print("P(sat | cat) =", P("cat", "sat"))
print("P(mat | sat) =", P("sat", "mat"))

